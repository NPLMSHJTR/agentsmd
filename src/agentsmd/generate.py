"""Render a detected repository into an AGENTS.md draft.

Two rules shape the output:

1. Every statement is traceable to a file. A line that cannot be traced is not
   written, even if it sounds useful.
2. No advice. "Write clean code" and "prefer small functions" are not facts and
   an agent cannot act on them, so they are omitted. The sections that remain
   are the ones an agent would otherwise have to discover by trial and error.

The generated file is explicitly a draft. It ends with a checklist of the things
detection cannot know, because pretending to fill those in is how these files
become fiction.
"""

from __future__ import annotations

from .detect import Repo


def _bullets(items: list[str]) -> str:
    return "\n".join(f"- {item}" for item in items)


# How each tool is actually invoked in its ecosystem. A tool name on its own is
# not runnable, so the generated file spells the invocation out.
INVOCATIONS = {
    "node": {
        "eslint": "npx eslint .",
        "prettier": "npx prettier --check .",
        "biome": "npx biome check .",
        "tsc": "npx tsc --noEmit",
    },
    "python": {
        "ruff": "ruff check .",
        "black": "black .",
        "mypy": "mypy .",
        "flake8": "flake8",
        "pylint": "pylint",
    },
    "rust": {
        "rustfmt": "cargo fmt --check",
        "clippy": "cargo clippy",
    },
    "go": {
        "golangci-lint": "golangci-lint run",
    },
}

# Tools that are run through the package manager instead of npx.
PM_WRAPPED = {
    "pnpm": {"eslint": "pnpm exec eslint .", "prettier": "pnpm exec prettier --check .",
             "biome": "pnpm exec biome check .", "tsc": "pnpm exec tsc --noEmit"},
    "yarn": {"eslint": "yarn exec eslint .", "prettier": "yarn exec prettier --check .",
             "tsc": "yarn exec tsc --noEmit"},
    "poetry": {"pytest": "poetry run pytest", "ruff": "poetry run ruff check .",
               "black": "poetry run black .", "mypy": "poetry run mypy ."},
    "uv": {"pytest": "uv run pytest", "ruff": "uv run ruff check .",
           "black": "uv run black .", "mypy": "uv run mypy ."},
}


def _invoke(tool: str, repo: Repo) -> str:
    """Turn a tool name into a command this repository would actually run."""
    if repo.package_manager in PM_WRAPPED:
        mapped = PM_WRAPPED[repo.package_manager].get(tool)
        if mapped:
            return mapped
    mapped = INVOCATIONS.get(repo.ecosystem or "", {}).get(tool)
    if mapped:
        return mapped
    return tool


def render(repo: Repo) -> str:
    parts: list[str] = []

    title = repo.root.resolve().name
    parts.append(f"# AGENTS.md\n")
    parts.append(
        "<!-- Generated by agentsmd from files on disk. Every line below is "
        "traceable to a file in this repository. Run `agentsmd verify` after "
        "changing the build. -->\n"
    )
    parts.append(
        "This file tells a coding agent how this specific repository works, so "
        "it does not have to rediscover the setup on every task.\n"
    )

    # --- Project -----------------------------------------------------------
    facts: list[str] = []
    if repo.ecosystem:
        facts.append(f"- Primary ecosystem: **{repo.ecosystem}**")
    if repo.package_manager:
        facts.append(f"- Package manager: **{repo.package_manager}**")
    if facts:
        parts.append("## Project\n")
        parts.append(_bullets([f[2:] for f in facts]))
        parts.append("")

    # --- Commands ----------------------------------------------------------
    parts.append("## Commands\n")
    parts.append(
        "These are the exact commands. Do not substitute a global tool for the "
        "project-local one.\n"
    )
    commands: list[str] = []
    if repo.test_command:
        commands.append(f"- Test: `{repo.test_command}`")
    else:
        commands.append(
            "- Test: **not detected.** Find the test entry before assuming one; "
            "do not invent a command."
        )
    if repo.lint_tools:
        # Write lint and format as runnable invocations, not bare tool names.
        # A bare name is not a command, and a document that lists one reads as
        # authoritative while being unusable.
        commands.append(
            "- Lint: " + ", ".join(f"`{_invoke(t, repo)}`" for t in repo.lint_tools)
        )
    if repo.formatters:
        commands.append(
            "- Format: " + ", ".join(f"`{_invoke(t, repo)}`" for t in repo.formatters)
        )
    parts.append(_bullets([c[2:] for c in commands]))
    parts.append("")

    # --- Layout ------------------------------------------------------------
    if repo.top_dirs:
        parts.append("## Layout\n")
        parts.append(
            "Top-level directories, excluding tooling directories: "
            + ", ".join(f"`{d}`" for d in repo.top_dirs)
            + "\n"
        )

    # --- Entrypoints -------------------------------------------------------
    if repo.entrypoints:
        parts.append("## Entrypoints\n")
        parts.append(_bullets([e.lstrip("- ") for e in repo.entrypoints]))
        parts.append("")

    # --- Do not edit -------------------------------------------------------
    if repo.generated_markers:
        parts.append("## Do not edit\n")
        parts.append(
            "These files declare themselves generated. A change here is "
            "overwritten on the next build:\n"
        )
        parts.append(_bullets([f"`{p}`" for p in repo.generated_markers]))
        parts.append("")

    # --- CI ----------------------------------------------------------------
    if repo.ci_files:
        parts.append("## Continuous integration\n")
        parts.append(
            "The build that must pass: " + ", ".join(f"`{c}`" for c in repo.ci_files)
        )
        parts.append("")

    # --- Notes about detection limits --------------------------------------
    if repo.notes:
        parts.append("## Detection notes\n")
        parts.append(
            "Where a value was inferred rather than read directly, it is "
            "recorded here so you can confirm it:\n"
        )
        parts.append(_bullets(repo.notes))
        parts.append("")

    # --- The honest part ---------------------------------------------------
    parts.append("## Not covered by this file\n")
    parts.append(
        "Detection reads files. It cannot know the following, and neither can "
        "an agent until someone writes it down:\n"
    )
    parts.append(
        _bullets(
            [
                "Which conventions are enforced in review but not by a linter",
                "Which parts of the codebase are fragile, deprecated, or off limits",
                "What the definition of done is for this project",
                "Which commands are safe to run against production data",
                "Domain vocabulary that a newcomer would misread",
            ]
        )
    )
    parts.append("")
    parts.append(
        "Add those by hand. Keep them short and specific: an instruction an "
        "agent cannot follow is worse than no instruction, because it looks "
        "like guidance and costs a turn to disprove.\n"
    )

    return "\n".join(parts)