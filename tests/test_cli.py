"""Tests for the generator and the CLI contract."""

from __future__ import annotations

import json
from pathlib import Path

from agentsmd.cli import main
from agentsmd.detect import detect
from agentsmd.generate import render


# --- generator --------------------------------------------------------------


def test_render_includes_commands_and_layout(node_repo: Path):
    text = render(detect(node_repo))
    assert "pnpm test" in text
    assert "`src/`" in text
    assert "eslint" in text


def test_render_is_explicit_about_what_it_cannot_know(node_repo: Path):
    """The honest section is the product. Without it the file looks complete."""
    text = render(detect(node_repo))
    assert "Not covered by this file" in text
    assert "definition of done" in text


def test_render_does_not_invent_a_test_command(empty_repo: Path):
    text = render(detect(empty_repo))
    assert "not detected" in text
    assert "do not invent a command" in text


def test_render_marks_itself_generated(node_repo: Path):
    text = render(detect(node_repo))
    assert "Generated by agentsmd" in text


def test_render_lists_detection_notes(node_repo: Path):
    text = render(detect(node_repo))
    assert "Detection notes" in text


# --- CLI: generate ----------------------------------------------------------


def test_generate_writes_file(node_repo: Path, capsys):
    assert main(["generate", str(node_repo)]) == 0
    assert (node_repo / "AGENTS.md").exists()
    assert "wrote" in capsys.readouterr().out


def test_generate_refuses_to_overwrite(node_repo: Path, capsys):
    (node_repo / "AGENTS.md").write_text("mine\n", encoding="utf-8")
    assert main(["generate", str(node_repo)]) == 2
    assert "already exists" in capsys.readouterr().err
    assert (node_repo / "AGENTS.md").read_text(encoding="utf-8") == "mine\n"


def test_generate_force_overwrites(node_repo: Path):
    (node_repo / "AGENTS.md").write_text("mine\n", encoding="utf-8")
    assert main(["generate", str(node_repo), "--force"]) == 0
    assert "Generated by agentsmd" in (node_repo / "AGENTS.md").read_text(
        encoding="utf-8"
    )


def test_generate_stdout_does_not_write(node_repo: Path, capsys):
    assert main(["generate", str(node_repo), "--stdout"]) == 0
    assert not (node_repo / "AGENTS.md").exists()
    assert "AGENTS.md" in capsys.readouterr().out


# --- CLI: detect ------------------------------------------------------------


def test_detect_emits_json(node_repo: Path, capsys):
    assert main(["detect", str(node_repo)]) == 0
    payload = json.loads(capsys.readouterr().out)
    assert payload["ecosystem"] == "node"
    assert payload["package_manager"] == "pnpm"


# --- CLI: verify ------------------------------------------------------------


def test_verify_missing_file_exits_two(empty_repo: Path, capsys):
    assert main(["verify", str(empty_repo)]) == 2
    assert "no AGENTS.md" in capsys.readouterr().err


def test_verify_clean_exits_zero(node_repo: Path, capsys):
    (node_repo / "AGENTS.md").write_text(
        "# AGENTS.md\n\nRun `pnpm test`. Layout: `src/`.\n", encoding="utf-8"
    )
    assert main(["verify", str(node_repo), "--no-color"]) == 0


def test_verify_broken_path_exits_one(node_repo: Path, capsys):
    (node_repo / "AGENTS.md").write_text(
        "# AGENTS.md\n\nSee `src/missing.ts`. Run `pnpm test`.\n", encoding="utf-8"
    )
    assert main(["verify", str(node_repo), "--no-color"]) == 1


def test_verify_json_shape(node_repo: Path, capsys):
    (node_repo / "AGENTS.md").write_text(
        "# AGENTS.md\n\nSee `src/missing.ts`.\n", encoding="utf-8"
    )
    main(["verify", str(node_repo), "--format", "json"])
    payload = json.loads(capsys.readouterr().out)
    assert set(payload) == {"path", "checked_items", "summary", "issues"}
    assert payload["summary"]["errors"] >= 1
    assert set(payload["issues"][0]) == {"rule", "severity", "message", "hint", "line"}


def test_verify_strict_fails_on_warning(node_repo: Path):
    (node_repo / "AGENTS.md").write_text(
        "# AGENTS.md\n\nPlease write clean readable code.\n", encoding="utf-8"
    )
    assert main(["verify", str(node_repo), "--no-color"]) == 0
    assert main(["verify", str(node_repo), "--no-color", "--strict"]) == 1


def test_round_trip_generate_then_verify(node_repo: Path, capsys):
    """A freshly generated file must not fail its own verifier."""
    assert main(["generate", str(node_repo)]) == 0
    capsys.readouterr()
    code = main(["verify", str(node_repo), "--no-color"])
    assert code == 0, capsys.readouterr().out