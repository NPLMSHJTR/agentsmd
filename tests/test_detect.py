def test_ci_files_detected(tmp_path: Path):
    (tmp_path / "pyproject.toml").write_text("[project]\nname='x'\n", encoding="utf-8")
    (tmp_path / ".github" / "workflows").mkdir(parents=True)
    repo = detect(tmp_path)
    assert ".github/workflows" in repo.ci_files


def test_command_exists_known_tool():
    found, _ = command_exists("python --version", Path("."))
    assert found


def test_command_exists_missing_tool():
    found, detail = command_exists("definitely-not-a-real-tool-xyz", Path("."))
    assert not found
    assert "not found" in detail


def test_command_exists_repo_relative_path(tmp_path: Path):
    (tmp_path / "scripts").mkdir()
    (tmp_path / "scripts" / "run.sh").write_text("", encoding="utf-8")
    found, _ = command_exists("./scripts/run.sh", tmp_path)
    assert found
    missing, detail = command_exists("./scripts/gone.sh", tmp_path)
    assert not missing
    assert "no such file" in detail